/** 絵の 1 層。線だけの層・塗りだけの層・両方の層がある */
export interface MotifLayer {
  /** SVG の path。`viewBox` は `0 0 100 100`、中心 (50,50) */
  d: string;
  /** 塗りの色。実際には `motifFill` で 22% に薄めて使う */
  fill?: string;
  stroke?: string;
  /** 線の太さ。省略時は 7 */
  w?: number;
}

export interface PrefectureMotif {
  /** その県の主色 */
  hue: string;
  layers: readonly MotifLayer[];
}

/** 線の太さの既定値。層ごとに `w` で上書きできる */
export const MOTIF_STROKE_WIDTH = 7;

/** 塗りの薄さ。22% だけ使い、残りは透明にして背景と混ぜる */
export const MOTIF_FILL_PERCENT = 22;

/**
 * 塗りの色。
 *
 * 【初心者向け】`color-mix` は「この色を N% だけ、残りはこの色」という書き方です。
 * 残りを `transparent` にすると**下の背景が透ける**ので、ライトでは淡く、ダークでは深く
 * 見えます。ライト用とダーク用に色を 2 組持たなくて済みます。
 */
export function motifFill(color: string): string {
  return `color-mix(in srgb, ${color} ${MOTIF_FILL_PERCENT}%, transparent)`;
}

