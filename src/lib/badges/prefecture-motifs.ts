/**
 * 県名から絵を引く。**無い県は `null`**。
 *
 * 【初心者向け】`null` を返せることが、この関数のいちばん大事なところです。
 * 呼ぶ側は `null` のとき **🏅 のまま**にします（要件 8 章 102）。こうしておけば、
 * 47 県の絵が揃うのを待たずに実装を進められ、あとから 1 県ずつ差し替えられます。
 * まだ決まっていない県（埼玉・富士山をどちらに置くか）も、ここを直すだけで済みます。
 */
export function prefectureMotif(prefecture: string): PrefectureMotif | null {
  return MOTIFS[prefecture] ?? null;
}

/** 絵を持っている県の数（画面の説明や検査に使う） */
export function motifPrefectureCount(): number {
  return Object.keys(MOTIFS).length;
}

/** 絵を持っている県の名前（検査用。並びは北から） */
export function motifPrefectureNames(): string[] {
  return Object.keys(MOTIFS);
}
