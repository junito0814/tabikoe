/**
 * #810（2026-10-06）: 画面に出す言葉（1 か所にまとめる）
 * 出典: Issue #810「画面に出す言葉を統一する」
 *       要件定義書 1.3「画面に出す言葉」・4.5.15（記号と文言の統一）
 *
 * 【初心者向け】同じ意味のことが画面ごとに違う言葉で書かれていました
 * （「ここを投稿」と「ここに投稿」、「投稿一覧」と「投稿を見る」、「保存する」と「行きたい」…）。
 * 読む人には**別のもの**に見えます。
 *
 * ここに置いて画面はここから読む、とすれば、次に変えたくなったときも 1 か所で済みます（約束 14）。
 */
export const TERMS = {
  /** 今いる場所に投稿する入口（ホーム・地図） */
  postHere: "＋ ここに投稿",
  /** そのスポットの投稿を見に行く（スポットカード・しおりの行の ⋯・戻り先） */
  seePosts: "投稿を見る",
  /** そのスポットに投稿する */
  post: "投稿する",
  /** 行きたい（♡の保存）。「保存する」「保存済み」「保存先」とは言わない */
  wishlist: "行きたい",
  /** 消す（投稿・コメント・しおり・アルバムそのもの） */
  delete: "削除",
  /** 1 つ抜く（しおり・行きたい・アルバムから） */
  remove: "外す",
  /** 自分が抜ける */
  leave: "退出",
  /** 招待リンクを使えなくする。「無効化」とは言わない */
  revoke: "取り消し",
  /** 絞り込みの条件を消す。「クリア」とは言わない */
  clearFilters: "条件を消す",
} as const;

/**
 * 件数の書き方。**数字の前後に半角空白**を入れる（「3 件」）。
 *
 * 【初心者向け】日本語と数字が続くと詰まって読みにくいので空けます。
 * 画面のあちこちで `{n}件` と直に書いていたので、ここに寄せました。
 */
export function countLabel(count: number, unit = "件"): string {
  return `${count.toLocaleString("ja-JP")} ${unit}`;
}
