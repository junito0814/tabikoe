/**
 * 出典: #705（6 桁を通しても管理画面に入れず、同じ画面に戻る）
 * 要件定義書 3.10.1「管理者ログイン」・7.1（性能のための `staleTimes`）
 *
 * ログインや同意の状態が変わった直後の移動は、**ブラウザのキャッシュを通さず読み込み直す**。
 *
 * 【初心者向け】なぜ `router.replace` ではだめなのか。
 * `next.config.ts` に `experimental.staleTimes.dynamic = 30` があり、**一度開いた画面の結果が
 * ブラウザ側に 30 秒間とどまる**（戻るが速くなる仕組み）。
 *
 * ところが「/admin を開いたら /admin/mfa へ飛ばされた」という**飛ばされた結果まで**とどまる。
 * そのため 6 桁が通ったあとに `router.replace("/admin")` を呼んでも、**とどまっている
 * 「飛ばす」結果がそのまま使われ、また 6 桁の画面に戻る**。`router.refresh()` はそのあとに
 * 走るので間に合わない。再読み込みで入れたのは、キャッシュを通らないため。
 *
 * 関所（`src/proxy.ts`）の判断が変わる場面では、素直に読み込み直すほうが確実。
 * 画面の移動が 1 か所にまとまっていれば、テストでも差し替えられる。
 */
export function hardRedirect(href: string): void {
  window.location.assign(href);
}
