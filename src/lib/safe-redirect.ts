/**
 * ログイン後の遷移先として安全なパスのみを許可する。
 * 外部ドメインへのオープンリダイレクトを防ぐため、アプリ内のパスだけを通す。
 *
 * #997（2026-10-18）: 判定を「ブラウザが読む形にそろえてから見る」形に直した。
 *
 * 【初心者向け】ここが守っているのは「**ログインしたら知らないサイトに飛んでいた**」を防ぐことです。
 * 遷移先は URL のクエリ（`?redirect_to=...`）で運ばれるので、**外から好きな値を入れられます**。
 *
 * 難しいのは、**ブラウザは URL を字面どおりに読まない**ことです。読む前に次のことをします。
 *   1. タブ・改行・復帰（目に見えない文字）を**捨てる**
 *   2. `\`（円記号・バックスラッシュ）を `/` と**同じものとして扱う**
 *
 * そのため「先頭が `/` か」だけを字面で見ると、ブラウザが読んだあとには別の意味に
 * なっている文字列を通してしまいます。**ブラウザと同じ下ごしらえをしてから見る**のがこの関数です。
 */

/** ブラウザが URL を読む前に捨てる文字（タブ・改行・復帰） */
const IGNORED_BY_BROWSER = /[\t\n\r]/g;

export function safeRedirectPath(path: string | null): string {
  if (!path) return "/";

  // ① ブラウザが捨てる文字は、こちらも先に捨てる
  const cleaned = path.replace(IGNORED_BY_BROWSER, "");

  /*
   * ② 先頭の 2 文字だけを、`\` を `/` にそろえて見る。
   *
   * 【初心者向け】2 文字で足りるのは、外に出られるかどうかが**先頭 2 文字で決まる**からです。
   *   - `/` 1 つで始まる … 同じサイトの中のパス（通す）
   *   - `/` が 2 つ続く  … 「次に来るのはサイト名」の意味になる（通さない）
   * 3 文字目以降の `\` は、同じサイトの中の移動にしかならないので触りません
   * （クエリに入った `\` を書き換えてしまわないためでもあります）。
   */
  const head = cleaned.slice(0, 2).replace(/\\/g, "/");
  if (!head.startsWith("/") || head.startsWith("//")) {
    return "/";
  }

  return cleaned;
}
