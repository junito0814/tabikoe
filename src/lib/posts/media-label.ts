/**
 * #937（2026-10-16）: 画面に出す「写真」「写真・動画」の言い方を 1 か所にまとめる
 * 出典: Issue #937、要件定義書 5.4
 *
 * 【初心者向け】動画の受け付けは環境変数（`VIDEO_UPLOAD_DISABLED`）で止められます。
 * 止めている間は「写真」、受け付けているときは「写真・動画」と出したいのですが、
 * **投稿画面だけが連動していて、アルバムの写真一覧などは「写真・動画」と手で書いてありました**。
 * 止めた環境では表示がずれ、動画を出す・止めるたびに直す場所が増えます（約束 14）。
 *
 * ここは**純粋関数だけ**です（約束 13）。`isVideoUploadDisabled()` はサーバーでしか読めないので、
 * 読むのはサーバー側（page.tsx）にまかせ、この関数は**受け取った真偽値から言葉を作るだけ**にします。
 */
export function mediaLabel(videoEnabled: boolean): "写真" | "写真・動画" {
  return videoEnabled ? "写真・動画" : "写真";
}
